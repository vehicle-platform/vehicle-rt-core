#!/usr/bin/env python3
"""Golden vector integrity check (QUALITY FW-3).

tests/host/vectors/*.h are generated by vehicle-server and copied here. Each header's first
line carries `content-sha256: <hex>`, the SHA-256 of the rest of the file (everything after
the first line). tests/host/vectors/MANIFEST.sha256 is a copy of vehicle-server's
tests/golden/MANIFEST.sha256 (`<content-sha256>  <file>`, plus a `defs vX.Y.Z` line).

Fails when a vector was hand-edited or is stale: body hash != banner hash, banner hash !=
manifest hash, a vector missing from the manifest, or a manifest entry without a file.
  tools/check_vectors.py [--server <path to vehicle-server MANIFEST.sha256>]
With --server the manifest must also equal the server's (local sync check, not run in CI).
"""
import hashlib
import re
import sys
from pathlib import Path

VEC = Path("tests/host/vectors")
BANNER = re.compile(r"content-sha256:\s*([0-9a-f]{64})")


def parse(path):
    ent, defs = {}, None
    for raw in Path(path).read_text(encoding="utf-8").splitlines():
        p = raw.split()
        if not p:
            continue
        if p[0] == "defs":
            defs = p[1]
        else:
            ent[p[1]] = p[0]
    return ent, defs


def main():
    ent, defs = parse(VEC / "MANIFEST.sha256")
    bad = []
    files = sorted(p.name for p in VEC.glob("*.h"))
    for f in files:
        data = (VEC / f).read_bytes()
        first, _, body = data.partition(b"\n")
        m = BANNER.search(first.decode("utf-8", "replace"))
        if f not in ent:
            bad.append("%s: not in MANIFEST.sha256" % f)
            continue
        if not m:
            bad.append("%s: no content-sha256 banner" % f)
            continue
        if hashlib.sha256(body).hexdigest() != m.group(1):
            bad.append("%s: content differs from its banner hash (edited or stale)" % f)
        if m.group(1) != ent[f]:
            bad.append("%s: banner hash differs from MANIFEST.sha256" % f)
    for f in sorted(set(ent) - set(files)):
        bad.append("%s: in MANIFEST.sha256 but file missing" % f)
    if "--server" in sys.argv:
        s_ent, s_defs = parse(sys.argv[sys.argv.index("--server") + 1])
        if (s_ent, s_defs) != (ent, defs):
            bad.append("MANIFEST.sha256 differs from the vehicle-server manifest")
    for b in bad:
        print("::error::" + b)
    print("vectors: %d files, defs %s, %d problems" % (len(files), defs, len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
